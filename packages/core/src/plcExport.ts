// PLC exports per station: I/O list (CSV), TIA Portal tag table (.xlsx),
// Codesys GVL, GX Works3 global labels. See docs/plc.md.
import { strToU8, zipSync } from 'fflate';
import type { PlcChannelInfo, PlcCardInfo } from './plc.js';
import { plcIoRows, reportToCsv, type ReportContext } from './reports.js';
import type { FormDefinition, IoKind, PlcStation } from './schema.js';
import { localize } from './text.js';

export type PlcExportFormat = 'csv' | 'tia' | 'codesys' | 'gxworks3';

export interface PlcExportFile {
  fileName: string;
  mimeType: string;
  content: string | Uint8Array;
}

/** Export formats that fit a station's PLC family (the CSV I/O list fits all). */
export function exportFormats(station: PlcStation): PlcExportFormat[] {
  const vendor = { siemens: 'tia', codesys: 'codesys', mitsubishi: 'gxworks3' } as const;
  return ['csv', vendor[station.family]];
}

interface ExportChannel {
  card: PlcCardInfo;
  info: PlcChannelInfo;
  comment: string;
}

function channelsOf(ctx: ReportContext, station: PlcStation, language: string): ExportChannel[] {
  const { languages } = ctx.state.project.settings;
  return ctx.plc.cards
    .filter((card) => card.station?.name === station.name)
    .sort((a, b) => (a.slot ?? 9999) - (b.slot ?? 9999))
    .flatMap((card) => card.channels.map((info) => ({ card, info, comment: localize(info.function, language, languages) })));
}

function station(ctx: ReportContext, name: string): PlcStation {
  const found = ctx.state.project.plcs.find((s) => s.name === name);
  if (!found) throw new Error(`PLC "${name}" not found`);
  return found;
}

export function exportPlc(ctx: ReportContext, stationName: string, format: PlcExportFormat, language: string, ioListForm?: FormDefinition): PlcExportFile {
  const s = station(ctx, stationName);
  const base = `${ctx.state.project.name}-${s.name}`.replace(/[^\p{L}\p{N}._-]+/gu, '_');
  switch (format) {
    case 'csv': {
      const rows = plcIoRows(ctx, s.name);
      const form = ioListForm ?? ctx.library.form('iec.form.plcIoList');
      if (!form) throw new Error('The I/O list form iec.form.plcIoList is missing');
      return { fileName: `${base}-io-list.csv`, mimeType: 'text/csv', content: reportToCsv(form, rows, language) };
    }
    case 'tia':
      return { fileName: `${base}-tags.xlsx`, mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', content: tiaTagTable(ctx, s, language) };
    case 'codesys':
      return { fileName: `${base}.gvl.txt`, mimeType: 'text/plain', content: codesysGvl(ctx, s, language) };
    case 'gxworks3':
      return { fileName: `${base}-labels.csv`, mimeType: 'text/csv', content: gxWorks3Labels(ctx, s, language) };
  }
}

// ---------------------------------------------------------------------------
// Siemens TIA Portal: PLC tag table for "Import" in the tag table editor

const TIA_TYPES: Record<IoKind, string> = { DI: 'Bool', DO: 'Bool', AI: 'Int', AO: 'Int' };

export function tiaTagTable(ctx: ReportContext, s: PlcStation, language: string): Uint8Array {
  if (s.family !== 'siemens') throw new Error(`${s.name} is not a Siemens PLC`);
  const header = ['Name', 'Path', 'Data Type', 'Logical Address', 'Comment', 'Hmi Visible', 'Hmi Accessible', 'Hmi Writeable', 'Typeobject ID', 'Version ID'];
  const rows = channelsOf(ctx, s, language)
    .filter(({ info }) => info.address)
    .map(({ info, comment }) => [
      info.name,
      `Wirewright ${s.name}`,
      info.channel.dataType ?? TIA_TYPES[info.channel.kind],
      `%${info.address}`,
      comment,
      'True',
      'True',
      'True',
      '',
      '',
    ]);
  return xlsx('PLC Tags', [header, ...rows]);
}

// ---------------------------------------------------------------------------
// Codesys: global variable list with direct addresses

const CODESYS_TYPES: Record<IoKind, string> = { DI: 'BOOL', DO: 'BOOL', AI: 'INT', AO: 'INT' };

export function codesysGvl(ctx: ReportContext, s: PlcStation, language: string): string {
  if (s.family !== 'codesys') throw new Error(`${s.name} is not a Codesys PLC`);
  const lines = [`// I/O of ${s.name} – generated by Wirewright from "${ctx.state.project.name}"`, '{attribute \'qualified_only\'}', 'VAR_GLOBAL'];
  for (const { card, info, comment } of channelsOf(ctx, s, language)) {
    if (!info.address) continue;
    const type = info.channel.dataType ?? CODESYS_TYPES[info.channel.kind];
    const note = [comment, `${card.device} ${info.channel.label ?? `${info.channel.kind} ${info.channel.channel}`} pin ${info.channel.pin}`].filter(Boolean).join(' – ');
    lines.push(`\t${info.name} AT ${info.address} : ${type}; (* ${note.replace(/\*\)/g, '* )')} *)`);
  }
  lines.push('END_VAR', '');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Mitsubishi GX Works3: global labels assigned to X/Y devices

const GX_TYPES: Record<IoKind, string> = { DI: 'Bit', DO: 'Bit', AI: 'Word [Signed]', AO: 'Word [Signed]' };

/**
 * Global labels as a tab-separated table with the columns of the GX Works3
 * global label editor (Label Name, Data Type, Class, Assign, Initial Value,
 * Constant, Comment), for pasting into the editor or importing.
 */
export function gxWorks3Labels(ctx: ReportContext, s: PlcStation, language: string): string {
  if (s.family !== 'mitsubishi') throw new Error(`${s.name} is not a Mitsubishi PLC`);
  const rows = [['Label Name', 'Data Type', 'Class', 'Assign (Device/Label)', 'Initial Value', 'Constant', 'Comment']];
  for (const { info, comment } of channelsOf(ctx, s, language)) {
    rows.push([info.name, info.channel.dataType ?? GX_TYPES[info.channel.kind], 'VAR_GLOBAL', info.address ?? '', '', '', comment]);
  }
  return '﻿' + rows.map((r) => r.map((v) => v.replace(/[\t\r\n]+/g, ' ')).join('\t')).join('\r\n') + '\r\n';
}

// ---------------------------------------------------------------------------
// Minimal .xlsx writer (one sheet, inline strings)

export function xlsx(sheetName: string, rows: string[][]): Uint8Array {
  const esc = (t: string) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  const col = (i: number): string => (i >= 26 ? col(Math.floor(i / 26) - 1) : '') + String.fromCharCode(65 + (i % 26));
  const sheetRows = rows
    .map((row, r) => `<row r="${r + 1}">${row.map((v, c) => `<c r="${col(c)}${r + 1}" t="inlineStr"><is><t xml:space="preserve">${esc(v)}</t></is></c>`).join('')}</row>`)
    .join('');
  const files: Record<string, string> = {
    '[Content_Types].xml':
      '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>',
    '_rels/.rels':
      '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>',
    'xl/workbook.xml': `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="${esc(sheetName)}" sheetId="1" r:id="rId1"/></sheets></workbook>`,
    'xl/_rels/workbook.xml.rels':
      '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/></Relationships>',
    'xl/worksheets/sheet1.xml': `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>${sheetRows}</sheetData></worksheet>`,
  };
  return zipSync(Object.fromEntries(Object.entries(files).map(([k, v]) => [k, strToU8(v)])));
}

